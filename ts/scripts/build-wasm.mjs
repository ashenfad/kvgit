#!/usr/bin/env node
/**
 * Build the core's WebAssembly binding into `wasm/`: compile
 * `crates/wasm` for wasm32, generate its JS glue with the wasm-bindgen
 * CLI, whose version must equal the `wasm-bindgen` crate's, and write
 * the module's bytes as a JS module (`kvgit_wasm_bytes.js`), so the
 * package loads it the same way under Node, bundlers and workers.
 *
 * Needs a Rust toolchain with the `wasm32-unknown-unknown` target and
 * `wasm-bindgen-cli` installed. Run via `pnpm build:wasm`.
 */

import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const pkgRoot = join(dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = join(pkgRoot, '..')
const target = 'wasm32-unknown-unknown'

function run(command, args) {
  const result = spawnSync(command, args, { cwd: repoRoot, stdio: 'inherit' })
  if (result.error) throw result.error
  if (result.status !== 0) process.exit(result.status ?? 1)
}

run('cargo', ['build', '--profile', 'wasm', '--target', target, '-p', 'kvgit-wasm'])
// No fallback URL for the module: the package always passes its bytes,
// and a bundler would try to resolve the URL to a file that isn't shipped.
run('wasm-bindgen', [
  '--target',
  'web',
  '--omit-default-module-path',
  '--out-dir',
  join(pkgRoot, 'wasm'),
  join(repoRoot, 'target', target, 'wasm', 'kvgit_wasm.wasm'),
])

const out = join(pkgRoot, 'wasm')
const base64 = readFileSync(join(out, 'kvgit_wasm_bg.wasm')).toString('base64')
writeFileSync(
  join(out, 'kvgit_wasm_bytes.js'),
  `// Generated by scripts/build-wasm.mjs: the core's WebAssembly module.
const BASE64 = '${base64}'

/** The module's bytes. */
export function wasmBytes() {
  const binary = atob(BASE64)
  const bytes = new Uint8Array(binary.length)
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i)
  return bytes
}
`,
)
writeFileSync(
  join(out, 'kvgit_wasm_bytes.d.ts'),
  `/** The core's WebAssembly module's bytes. */
export function wasmBytes(): Uint8Array<ArrayBuffer>
`,
)
